"""Emoji shortcodes: ``:tada:`` → 🎉, with GitHub's names and rules.

Names come from GitHub's gemoji database (``assets/emoji.json``, regenerated by
``scripts/update_emoji.py``). As on GitHub, names are case-sensitive, a shortcode preceded by
a letter, digit or colon is left alone (``a:tada:``, ``::tada:``) unless that colon closes
another emoji (``:smile::smile:``), and code spans, code blocks and image alt text are never
converted.
"""

from __future__ import annotations

import json
import re
from functools import cache
from importlib.resources import files

from markdown_it import MarkdownIt
from markdown_it.rules_core import StateCore

_SHORTCODE = re.compile(r":([a-z0-9_+-]+):")


@cache
def shortcodes() -> dict[str, str]:
    """GitHub's shortcode → emoji map."""
    data = json.loads(files("md2html").joinpath("assets/emoji.json").read_text(encoding="utf-8"))
    emoji: dict[str, str] = data["emoji"]
    return emoji


def replace_shortcodes(text: str) -> str:
    """Replace the shortcodes in a run of plain text."""
    names = shortcodes()
    parts: list[str] = []
    position = 0
    last_emoji_end = -1
    for match in _SHORTCODE.finditer(text):
        start = match.start()
        before = text[start - 1] if start else ""
        emoji = names.get(match.group(1))
        if emoji is None or (start != last_emoji_end and (before.isalnum() or before == ":")):
            continue
        parts += [text[position:start], emoji]
        position = last_emoji_end = match.end()
    parts.append(text[position:])
    return "".join(parts)


def emoji_plugin(md: MarkdownIt) -> None:
    """Register the emoji rule before heading anchors, so slugs see the emoji, not its name."""
    md.core.ruler.before("anchor", "emoji", _emoji)


def _emoji(state: StateCore) -> None:
    for token in state.tokens:
        if token.type != "inline":
            continue
        # Only direct children: an image's alt text lives in its own children and stays as is.
        for child in token.children or []:
            if child.type == "text" and ":" in child.content:
                child.content = replace_shortcodes(child.content)
